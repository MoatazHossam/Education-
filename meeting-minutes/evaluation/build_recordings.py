"""Builds the evaluation recordings in evaluation/recordings from the hand-written scenarios.

Two kinds of audio, both with a reference transcript (times, speakers, words) written by people,
never generated by the system under test:

* Scenario meetings (scenarios/*.json): each turn is spoken by Piper's Arabic voice (ar_JO-kareem),
  turned into distinct voices by shifting pitch and timbre, laid out with pauses and, where the
  scenario says so, overlapping the previous turn. A degraded copy of s1 adds noise and telephone
  bandwidth. These test the *meeting* logic (decisions vs proposals, owners, dates) with a known
  answer; they are synthetic speech, not natural conversation.
* fleurs_ar_eg: real human Egyptian Arabic read speech from Google's FLEURS dataset (CC BY 4.0,
  https://huggingface.co/datasets/google/fleurs), utterances concatenated. It tests recognition on
  real voices only: FLEURS does not identify its readers (and its ar_eg readers are all female), so
  this recording carries no speaker ground truth and is not used for diarization scores.

Real recorded meetings, reviewed by people, must be added before relying on the numbers
(docs/EVALUATION.md).

Usage (a separate environment with piper-tts):  python build_recordings.py --voice-dir DIR [--fleurs-dir DIR]
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import random
import subprocess
import wave
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
OUT = HERE / "recordings"
SR = 22050
# Pitch/timbre transforms (rate factor, tempo correction): v1 is the voice as it is.
VOICES = {"v1": None, "v2": 0.86, "v3": 1.17, "v4": 0.93}
VOICE_SPEED = {"v1": 1.0, "v2": 1.05, "v3": 0.95, "v4": 1.1}


def synth(voice, text: str, length_scale: float) -> np.ndarray:
    from piper import SynthesisConfig

    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        voice.synthesize_wav(text, w, syn_config=SynthesisConfig(length_scale=length_scale, noise_scale=0.6, noise_w_scale=0.8))
    buf.seek(0)
    with wave.open(buf, "rb") as r:
        data = np.frombuffer(r.readframes(r.getnframes()), dtype=np.int16).astype(np.float32) / 32768
    return data


def transform(samples: np.ndarray, voice: str) -> np.ndarray:
    factor = VOICES[voice]
    if factor is None:
        return samples
    raw = samples.astype(np.float32).tobytes()
    af = f"asetrate={int(SR * factor)},aresample={SR},atempo={1 / factor:.5f}"
    out = subprocess.run(
        ["ffmpeg", "-v", "error", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "-", "-af", af, "-f", "f32le", "-"],
        input=raw, capture_output=True, check=True,
    ).stdout
    return np.frombuffer(out, dtype=np.float32)


def encode(samples: np.ndarray, sr: int, dst: Path, fmt: str, degraded: bool = False) -> None:
    raw = np.clip(samples, -1, 1).astype(np.float32).tobytes()
    if degraded:
        # Café-like noise at roughly 8 dB SNR, telephone bandwidth, low bitrate.
        af = ["-filter_complex",
              f"[0:a]aresample={sr}[s];anoisesrc=color=pink:amplitude=0.06:sample_rate={sr}:seed=7[n];"
              "[s][n]amix=inputs=2:duration=first:normalize=0,highpass=f=300,lowpass=f=3400,aresample=8000[o]",
              "-map", "[o]"]
        codec = ["-c:a", "libmp3lame", "-b:a", "24k"]
    else:
        af = []
        codec = {"mp3": ["-c:a", "libmp3lame", "-b:a", "48k"], "m4a": ["-c:a", "aac", "-b:a", "48k"],
                 "ogg": ["-c:a", "libopus", "-b:a", "32k"], "wav": ["-c:a", "pcm_s16le"]}[fmt]
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(sr), "-ac", "1", "-i", "-", *af, *codec, str(dst)],
                   input=raw, check=True)


def build_scenario(path: Path, voice) -> list[Path]:
    sc = json.loads(path.read_text(encoding="utf-8"))
    rng = random.Random(sc["id"])
    track = np.zeros(0, dtype=np.float32)
    cursor = 0.4
    ref_segments = []
    for i, turn in enumerate(sc["turns"]):
        v = sc["voices"][turn["speaker"]]
        audio = transform(synth(voice, turn.get("tts_text") or turn["text"], VOICE_SPEED[v]), v)
        start = cursor - turn["overlap"] if turn.get("overlap") and ref_segments else cursor
        a = int(start * SR)
        need = a + len(audio)
        if need > len(track):
            track = np.concatenate([track, np.zeros(need - len(track), dtype=np.float32)])
        track[a:need] += audio * 0.9
        end = start + len(audio) / SR
        ref_segments.append({"id": f"R{i + 1:03d}", "speaker": turn["speaker"], "start": round(start, 3), "end": round(end, 3),
                             "text": turn["text"], "overlap": bool(turn.get("overlap"))})
        cursor = max(cursor, end) + rng.uniform(0.35, 0.8)
    track = np.concatenate([track, np.zeros(int(0.6 * SR), dtype=np.float32)])
    fmt = sc.get("format", {"s2_egyptian_no_decision": "ogg"}.get(sc["id"], "mp3"))
    outputs = []
    dst = OUT / f"{sc['id']}.{fmt}"
    encode(track, SR, dst, fmt)
    outputs.append(dst)
    reference = {"id": sc["id"], "source": "synthetic (Piper ar_JO-kareem, pitch-shifted voices)", "scenario": path.name,
                 "duration": round(len(track) / SR, 3), "segments": ref_segments}
    (OUT / f"{sc['id']}.reference.json").write_text(json.dumps(reference, ensure_ascii=False, indent=1), encoding="utf-8")
    if sc["id"] == "s1_formal_decisions":
        deg = OUT / "s1_formal_decisions_degraded.mp3"
        encode(track, SR, deg, "mp3", degraded=True)
        (OUT / "s1_formal_decisions_degraded.reference.json").write_text(
            json.dumps({**reference, "id": "s1_formal_decisions_degraded", "source": reference["source"] + ", noise + telephone band"},
                       ensure_ascii=False, indent=1), encoding="utf-8")
        outputs.append(deg)
    return outputs


def build_fleurs(fleurs_dir: Path, count: int = 16) -> Path:
    rows = list(csv.reader(open(fleurs_dir / "dev.tsv", encoding="utf-8"), delimiter="\t"))
    picked, seen_text = [], set()
    for r in rows:
        if r[2] not in seen_text and (fleurs_dir / "dev" / r[1]).exists():
            picked.append(r)
            seen_text.add(r[2])
        if len(picked) == count:
            break
    sr = 16000
    track = np.zeros(int(0.4 * sr), dtype=np.float32)
    segments = []
    for i, r in enumerate(picked):
        raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(fleurs_dir / "dev" / r[1]), "-ac", "1", "-ar", str(sr), "-f", "f32le", "-"],
                             capture_output=True, check=True).stdout
        audio = np.frombuffer(raw, dtype=np.float32)
        start = len(track) / sr
        track = np.concatenate([track, audio, np.zeros(int(0.6 * sr), dtype=np.float32)])
        segments.append({"id": f"R{i + 1:03d}", "speaker": None, "start": round(start, 3),
                         "end": round(start + len(audio) / sr, 3), "text": r[2], "fleurs_file": r[1]})
    dst = OUT / "fleurs_ar_eg.mp3"
    encode(track, sr, dst, "mp3")
    (OUT / "fleurs_ar_eg.reference.json").write_text(json.dumps({
        "id": "fleurs_ar_eg", "source": "FLEURS ar_eg dev split (Google, CC BY 4.0); real read speech",
        "speaker_note": "No speaker ground truth: FLEURS does not identify readers. Used for recognition accuracy only.",
        "duration": round(len(track) / sr, 3), "segments": segments}, ensure_ascii=False, indent=1), encoding="utf-8")
    return dst


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice-dir", type=Path, required=True, help="folder with ar_JO-kareem-medium.onnx and .onnx.json")
    ap.add_argument("--fleurs-dir", type=Path, help="folder with dev.tsv and dev/*.wav of FLEURS ar_eg")
    args = ap.parse_args()
    from piper import PiperVoice

    OUT.mkdir(exist_ok=True)
    voice = PiperVoice.load(str(args.voice_dir / "ar_JO-kareem-medium.onnx"), config_path=str(args.voice_dir / "ar_JO-kareem-medium.onnx.json"))
    for sc in sorted((HERE / "scenarios").glob("*.json")):
        for p in build_scenario(sc, voice):
            print("built", p.name)
    if args.fleurs_dir:
        print("built", build_fleurs(args.fleurs_dir).name)


if __name__ == "__main__":
    main()
