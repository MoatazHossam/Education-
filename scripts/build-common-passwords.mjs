#!/usr/bin/env node
// Regenerates src/lib/common-passwords.ts from a pinned copy of a public list (production finding S-6).
//
//   node scripts/build-common-passwords.mjs
//
// The list: the UK National Cyber Security Centre's 100,000 passwords most often found in breaches
// (from Have I Been Pwned), as published in SecLists (MIT licence, (c) 2018 Daniel Miessler), at a fixed
// commit and checked against its SHA-256, so the result is the same on every run. The application
// never calls out: the list ships in the code.
//
// Kept: entries of 10 to 128 characters (shorter ones are refused by length already), lowercased,
// printable ASCII, without duplicates, in the list's order (most common first).
import { Buffer } from 'node:buffer';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { URL } from 'node:url';

const COMMIT = '48c951a3c3afba4e647bfe6944a1fbd2fdbf2ca7';
const PATH = 'Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt';
const SHA256 = 'c2e5696882c603b76bb67a47ee970897e5a76fc4c3f5547abe3d0ca340c576e0';
const OUT = new URL('../src/lib/common-passwords.ts', import.meta.url);

async function download(path) {
  const url = `https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/${path}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

const raw = await download(PATH);
const sha = createHash('sha256').update(raw).digest('hex');
if (sha !== SHA256) throw new Error(`Unexpected SHA-256 ${sha}; expected ${SHA256}`);
// The MIT licence asks for its notice to go with copies: it is kept in the generated file.
const licence = (await download('LICENSE')).toString('utf8').trim();
if (!licence.startsWith('MIT License')) throw new Error('SecLists LICENSE is no longer the MIT licence; review before use');

const kept = [];
const seen = new Set();
for (const line of raw.toString('utf8').split('\n')) {
  const p = line.replace(/\r$/, '').toLowerCase();
  if (p.length < 10 || p.length > 128 || !/^[\x20-\x7e]+$/.test(p) || seen.has(p)) continue;
  seen.add(p);
  kept.push(p);
}
// Inside a template literal: escape what would end it or start a placeholder.
const body = kept.map((p) => p.replace(/[\\`]/g, '\\$&').replace(/\$\{/g, '\\${')).join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/build-common-passwords.mjs; do not edit by hand.
// Source: SecLists (MIT licence, (c) 2018 Daniel Miessler) at commit ${COMMIT},
// ${PATH} (SHA-256 ${SHA256}):
// the UK National Cyber Security Centre's 100,000 passwords most often found in breaches.
// ${kept.length} entries of 10 to 128 characters, lowercased, most common first.
//
// SecLists' licence:
${licence.split('\n').map((l) => `// ${l}`.trimEnd()).join('\n')}
export const COMMON_PASSWORDS = \`${body}\`;
`,
);
console.log(`Wrote ${kept.length} passwords to ${OUT.pathname}`);
