const codeOnly = (segs) => (Array.isArray(segs) ? segs : [segs]).every((x) => typeof x === 'object' && x.c !== undefined);
function table(header, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const scaled = widths.map((w) => Math.floor((w / total) * TEXT_W));
  scaled[0] += TEXT_W - scaled.reduce((a, b) => a + b, 0);
  const cell = (segs, isHead, i) => new TableCell({
    width: { size: scaled[i], type: WidthType.DXA },
    shading: isHead ? { type: ShadingType.CLEAR, fill: '1F3A5F', color: 'auto' } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [codeOnly(segs)
      ? new Paragraph({ bidirectional: false, alignment: AlignmentType.LEFT, spacing: { after: 0, line: 276 }, children: (Array.isArray(segs) ? segs : [segs]).map((x) => new TextRun({ text: x.c, font: fonts(MONO), size: 17, sizeComplexScript: 17 })) })
      : new Paragraph({ bidirectional: true, spacing: { after: 0, line: 276 }, children: runs(segs, isHead ? { bold: true, boldComplexScript: true, color: 'FFFFFF' } : {}) })],
  });
  body.push(new Table({
    visuallyRightToLeft: true,
    width: { size: TEXT_W, type: WidthType.DXA },
    columnWidths: scaled,
    rows: [
      new TableRow({ tableHeader: true, children: header.map((hd, i) => cell(hd, true, i)) }),
      ...rows.map((r) => new TableRow({ cantSplit: true, children: r.map((c, i) => cell(c, false, i)) })),
    ],
  }));
  body.push(new Paragraph({ children: [], spacing: { after: 120 } }));
}
// Images: widths in pixels (96 per inch); the text column is about 600 px wide.
const size = (file) => { const b = readFileSync(file); let i = 2; while (i < b.length) { const m = b[i + 1]; const len = b.readUInt16BE(i + 2); if (m >= 0xc0 && m <= 0xc3) return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) }; i += 2 + len; } throw new Error(`no size in ${file}`); };
const imageRun = (name, width) => { const file = join(SHOTS, name); const s = size(file); return new ImageRun({ type: 'jpg', data: readFileSync(file), transformation: { width, height: Math.round((s.h / s.w) * width) } }); };
const caption = (text) => body.push(new Paragraph({ bidirectional: true, alignment: AlignmentType.CENTER, spacing: { after: 200 }, children: runs(text, { size: 18, sizeComplexScript: 18, color: '666666', italics: true }) }));
