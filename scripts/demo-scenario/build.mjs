// A segment is a string (Arabic), {c: 'code'} (left to right, monospace), {b: 'bold'} or {l: 'Latin text'}.
const LRM = '‎';
const ltr = (t) => `${/^[A-Za-z0-9]/.test(t) ? '' : LRM}${t}${/[A-Za-z0-9]$/.test(t) ? '' : LRM}`;
function runs(segs, base = {}) {
  const list = Array.isArray(segs) ? segs : [segs];
  return list.map((s) => {
    if (typeof s === 'string') return new TextRun({ text: s, rightToLeft: true, font: fonts(FONT), size: 22, sizeComplexScript: 22, ...base });
    if (s.c !== undefined) return new TextRun({ text: ltr(s.c), rightToLeft: false, font: fonts(MONO), size: 19, sizeComplexScript: 19, shading: { type: ShadingType.CLEAR, fill: 'EEF1F4', color: 'auto' } });
    if (s.l !== undefined) return new TextRun({ text: ltr(s.l), rightToLeft: false, font: fonts(FONT), size: 22, sizeComplexScript: 22, ...base });
    if (s.b !== undefined) return new TextRun({ text: s.b, rightToLeft: true, bold: true, boldComplexScript: true, font: fonts(FONT), size: 22, sizeComplexScript: 22, ...base });
    throw new Error(`bad segment ${JSON.stringify(s)}`);
  });
}
